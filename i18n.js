// Testo nella lingua scelta; se manca, quello italiano; se manca anche quello, la chiave
function t(key,vars){
  var s=I18N[LANG][key];
  if(s==null)s=I18N.it[key];
  if(s==null)s=key;
  return vars?String(s).replace(/\{(\w+)\}/g,function(m,k){return vars[k]!=null?vars[k]:m;}):s;
}
// Singolare/plurale: chiave.one per 1, chiave.other per il resto; {n} è il numero
function tn(key,n,vars){return t(key+(n===1?'.one':'.other'),Object.assign({n:n},vars||{}));}
// Testi fissi della pagina: data-i18n (testo), data-i18n-html (con markup), data-i18n-ph (placeholder), data-i18n-aria (aria-label)
function applyI18n(root){
  root=root||document;
  document.documentElement.lang=LANG;
  root.querySelectorAll('[data-i18n]').forEach(function(el){el.textContent=t(el.getAttribute('data-i18n'));});
  root.querySelectorAll('[data-i18n-html]').forEach(function(el){el.innerHTML=t(el.getAttribute('data-i18n-html'));});
  root.querySelectorAll('[data-i18n-ph]').forEach(function(el){el.setAttribute('placeholder',t(el.getAttribute('data-i18n-ph')));});
  root.querySelectorAll('[data-i18n-aria]').forEach(function(el){el.setAttribute('aria-label',t(el.getAttribute('data-i18n-aria')));});
}
